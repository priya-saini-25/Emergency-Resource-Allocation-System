process.env.NODE_ENV = 'test';
import test, { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import DispatchRecord from '../src/models/DispatchRecord.js';
import Incident from '../src/models/Incident.js';
import Resource from '../src/models/Resource.js';
import Hospital from '../src/models/Hospital.js';
import {
  persistRecommendationSnapshot
} from '../src/services/dispatchRecommendationService.js';
import {
  confirmDispatch,
  DispatchConfirmationError
} from '../src/services/dispatchExecutionService.js';
import { __setConnectionStateOverride } from '../src/config/database.js';

function createMockSession() {
  return {
    hasStarted: false,
    hasCommitted: false,
    hasAborted: false,
    hasEnded: false,
    startTransaction() {
      this.hasStarted = true;
    },
    async commitTransaction() {
      this.hasCommitted = true;
    },
    async abortTransaction() {
      this.hasAborted = true;
    },
    async endSession() {
      this.hasEnded = true;
    }
  };
}

describe('DispatchRecord Duplicate Key & dispatchId Regression Tests', () => {
  const operatorUser = {
    _id: '507f1f77bcf86cd799439088',
    id: '507f1f77bcf86cd799439088',
    name: 'Operator Dan',
    email: 'operator@jodhpur.emergency.gov.in',
    role: 'OPERATOR',
    isActive: true
  };

  it('should generate a valid, unique dispatchId for every new recommendation document', () => {
    const doc1 = new DispatchRecord({
      batchId: 'BATCH-TEST-001',
      totalIncidents: 1,
      includedIncidentIds: [1001]
    });

    const doc2 = new DispatchRecord({
      batchId: 'BATCH-TEST-002',
      totalIncidents: 1,
      includedIncidentIds: [1002]
    });

    assert.ok(doc1.dispatchId, 'doc1 must have a dispatchId generated by default');
    assert.ok(doc2.dispatchId, 'doc2 must have a dispatchId generated by default');
    assert.ok(doc1.dispatchId.startsWith('DISPATCH-'), 'dispatchId should follow DISPATCH- prefix format');
    assert.ok(doc2.dispatchId.startsWith('DISPATCH-'), 'dispatchId should follow DISPATCH- prefix format');
    assert.notEqual(doc1.dispatchId, doc2.dispatchId, 'Two independently generated documents must have distinct dispatchIds');
  });

  it('should successfully create multiple recommendation records in memory without duplicate dispatchId collisions', async () => {
    const createdRecords = [];
    const origSave = DispatchRecord.prototype.save;

    DispatchRecord.prototype.save = async function () {
      createdRecords.push(this);
      return this;
    };

    try {
      const mockEngineResponse = {
        success: true,
        data: {
          batch_id: 1,
          batch_status: 'SUCCESS',
          total_incidents_received: 1,
          valid_incidents: 1,
          invalid_incidents: 0,
          fully_allocated_incidents: 1,
          partially_allocated_incidents: 0,
          unallocated_incidents: 0,
          total_unique_resources_recommended: 1,
          total_hospital_recommendations: 1,
          incident_results: [
            {
              incident_id: 1001,
              processing_order: 1,
              dispatch_status: 'FULLY_ALLOCATED',
              priority: { total_priority_score: 50, tier: 'HIGH' },
              resource_allocation: {
                status: 'FULLY_ALLOCATED',
                selected_resources: [
                  {
                    resource_id: 101,
                    resource_type: 'ALS_AMBULANCE',
                    road_distance_meters: 1200,
                    estimated_eta_seconds: 150
                  }
                ],
                shortages: []
              },
              hospital_matching: null
            }
          ]
        },
        metadata: { totalExecutionTimeMs: 12 }
      };

      const mockIncidents = [{ incidentId: 1001, status: 'VERIFIED' }];

      // Create recommendation 1
      const rec1 = await persistRecommendationSnapshot(
        mockEngineResponse,
        operatorUser,
        mockIncidents,
        'REQ-1',
        'BATCH-DUP-001'
      );

      // Create recommendation 2 (simulate subsequent "Run C++ Optimization" click)
      const rec2 = await persistRecommendationSnapshot(
        mockEngineResponse,
        operatorUser,
        mockIncidents,
        'REQ-2',
        'BATCH-DUP-002'
      );

      // Create recommendation 3
      const rec3 = await persistRecommendationSnapshot(
        mockEngineResponse,
        operatorUser,
        mockIncidents,
        'REQ-3',
        'BATCH-DUP-003'
      );

      assert.equal(createdRecords.length, 3, 'Three records should be persisted');
      assert.ok(rec1.dispatchId, 'rec1 must have a non-null dispatchId');
      assert.ok(rec2.dispatchId, 'rec2 must have a non-null dispatchId');
      assert.ok(rec3.dispatchId, 'rec3 must have a non-null dispatchId');

      const dispatchIds = new Set([rec1.dispatchId, rec2.dispatchId, rec3.dispatchId]);
      assert.equal(dispatchIds.size, 3, 'All three dispatchIds must be completely unique');
    } finally {
      DispatchRecord.prototype.save = origSave;
    }
  });

  it('should enforce unique dispatchId when explicitly duplicating dispatchIds', async () => {
    const existingIds = new Set();

    const mockSaveWithUniqueCheck = async (doc) => {
      if (existingIds.has(doc.dispatchId)) {
        const err = new Error(`E11000 duplicate key error collection: emergency_response_jodhpur.dispatchrecords index: dispatchId_1 dup key: { dispatchId: "${doc.dispatchId}" }`);
        err.code = 11000;
        throw err;
      }
      existingIds.add(doc.dispatchId);
      return doc;
    };

    const docA = new DispatchRecord({
      dispatchId: 'DISPATCH-COLLISION-TEST',
      batchId: 'BATCH-COL-A',
      totalIncidents: 1,
      includedIncidentIds: [1]
    });

    const docB = new DispatchRecord({
      dispatchId: 'DISPATCH-COLLISION-TEST', // Same dispatchId!
      batchId: 'BATCH-COL-B',
      totalIncidents: 1,
      includedIncidentIds: [2]
    });

    await mockSaveWithUniqueCheck(docA);

    await assert.rejects(
      async () => {
        await mockSaveWithUniqueCheck(docB);
      },
      (err) => {
        assert.equal(err.code, 11000);
        assert.ok(err.message.includes('E11000 duplicate key error'));
        return true;
      }
    );
  });

  it('should protect failed recommendations from dispatch confirmation even with valid dispatchId', async () => {
    const origFindOne = DispatchRecord.findOne;
    DispatchRecord.findOne = async () => ({
      dispatchId: 'DISPATCH-FAILED-REGRESSION-01',
      batchId: 'BATCH-FAILED-REGRESSION-01',
      batchStatus: 'FAILED',
      recommendationStatus: 'FAILED',
      confirmationStatus: 'PENDING',
      batchStatusMessage: 'Zero resources allocated by C++ engine',
      incidentResults: [
        {
          incidentId: 9001,
          allocationStatus: 'NO_RESOURCES_AVAILABLE',
          assignedResources: []
        }
      ]
    });

    try {
      await assert.rejects(
        async () => {
          await confirmDispatch('BATCH-FAILED-REGRESSION-01', {}, operatorUser);
        },
        (err) => {
          assert.ok(err instanceof DispatchConfirmationError);
          assert.equal(err.code, 'CANNOT_CONFIRM_FAILED_BATCH');
          assert.equal(err.statusCode, 409);
          return true;
        }
      );
    } finally {
      DispatchRecord.findOne = origFindOne;
    }
  });

  it('should allow successful recommendation with valid dispatchId to proceed to confirmation', async () => {
    __setConnectionStateOverride({ connected: true, state: 'connected' });
    const mockSession = createMockSession();

    let confirmedDispatchId = null;

    const origRecFind = DispatchRecord.findOne;
    const origIncFind = Incident.find;
    const origIncFindOneAndUpdate = Incident.findOneAndUpdate;
    const origResFindOneAndUpdate = Resource.findOneAndUpdate;
    const origHospFindOneAndUpdate = Hospital.findOneAndUpdate;

    const originalDispatchId = 'DISPATCH-SUCCESS-REGRESSION-01';

    DispatchRecord.findOne = async (q) => {
      if (q && q.idempotencyKey) return null;
      return {
        dispatchId: originalDispatchId,
        batchId: 'BATCH-SUCCESS-REGRESSION-01',
        batchStatus: 'SUCCESS',
        recommendationStatus: 'RECOMMENDED',
        confirmationStatus: 'PENDING',
        includedIncidentIds: [9002],
        totalIncidents: 1,
        incidentResults: [
          {
            incidentId: 9002,
            allocationStatus: 'FULLY_ALLOCATED',
            assignedResources: [{ resourceId: 101, resourceType: 'ALS_AMBULANCE' }],
            resourceShortages: [],
            recommendedHospital: null
          }
        ],
        confirmationAuditTrail: [],
        save: async function () {
          confirmedDispatchId = this.dispatchId;
          return this;
        }
      };
    };

    Incident.find = async () => [{
      incidentId: 9002,
      status: 'VERIFIED',
      location: { latitude: 26.29, longitude: 73.02 },
      category: 'MEDICAL',
      severity: 3
    }];

    Incident.findOneAndUpdate = async () => ({ incidentId: 9002, status: 'DISPATCHED' });
    Resource.findOneAndUpdate = async () => ({ resourceId: 101, status: 'DISPATCHED', resourceType: 'ALS_AMBULANCE' });
    Hospital.findOneAndUpdate = async () => ({ hospitalId: 701, status: 'OPERATIONAL' });

    try {
      const result = await confirmDispatch(
        'BATCH-SUCCESS-REGRESSION-01',
        { confirmationNotes: 'Successful regression confirmation', sessionOverride: mockSession },
        operatorUser
      );

      assert.ok(result);
      assert.equal(result.confirmationStatus, 'CONFIRMED');
      assert.equal(confirmedDispatchId, originalDispatchId, 'Preserves existing valid dispatchId on confirmation');
      assert.equal(mockSession.hasCommitted, true, 'Transaction committed successfully');
    } finally {
      DispatchRecord.findOne = origRecFind;
      Incident.find = origIncFind;
      Incident.findOneAndUpdate = origIncFindOneAndUpdate;
      Resource.findOneAndUpdate = origResFindOneAndUpdate;
      Hospital.findOneAndUpdate = origHospFindOneAndUpdate;
      __setConnectionStateOverride(null);
    }
  });

  it('should verify schema indexes are configured with partialFilterExpression', () => {
    const indexes = DispatchRecord.schema.indexes();

    const dispatchIdIndex = indexes.find(([fields]) => fields.dispatchId !== undefined);
    assert.ok(dispatchIdIndex, 'dispatchId index must be defined');
    const [fields, options] = dispatchIdIndex;
    assert.equal(options.unique, true, 'dispatchId index must be unique');
    assert.deepEqual(
      options.partialFilterExpression,
      { dispatchId: { $type: 'string' } },
      'dispatchId index must have partialFilterExpression for string types'
    );

    const idempotencyKeyIndex = indexes.find(([fields]) => fields.idempotencyKey !== undefined);
    assert.ok(idempotencyKeyIndex, 'idempotencyKey index must be defined');
    const [, idempOptions] = idempotencyKeyIndex;
    assert.equal(idempOptions.unique, true, 'idempotencyKey index must be unique');
    assert.deepEqual(
      idempOptions.partialFilterExpression,
      { idempotencyKey: { $type: 'string' } },
      'idempotencyKey index must have partialFilterExpression for string types'
    );
  });
});
